"""Render the bundled background-music library.

    python render.py                 # every genre
    python render.py lofi jazz       # just these genres
    python render.py lofi:rainy-window --preview DIR   # one track, plus WAV + spectrogram

Writes public/music/<genre>/<slug>.mp3 and regenerates src/lib/music-library.ts.
Needs numpy, scipy, numba and lameenc (pip install numpy scipy numba lameenc).
"""

import importlib
import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

OUT = HERE.parent.parent / "public" / "music"
GENRES = ["lofi", "chill", "relax", "focus", "jazz", "ambient", "piano", "synthwave", "acoustic", "upbeat"]


def job(genre, slug, preview):
    import numpy as np

    from engine import SR, loudness
    from song import spectrogram_png, write_mp3, write_wav

    mod = importlib.import_module(f"genres.{genre}")
    cfg = next(c for c in mod.TRACKS if c["slug"] == slug)
    t0 = time.time()
    audio = mod.build(cfg)
    assert np.all(np.isfinite(audio)), f"{genre}/{slug}: non-finite samples"
    dest = OUT / genre
    dest.mkdir(parents=True, exist_ok=True)
    write_mp3(dest / f"{slug}.mp3", audio)
    if preview:
        p = Path(preview)
        p.mkdir(parents=True, exist_ok=True)
        write_wav(p / f"{genre}-{slug}.wav", audio)
        spectrogram_png(p / f"{genre}-{slug}.png", audio)
    return dict(
        genre=genre,
        slug=slug,
        title=cfg["title"],
        seconds=round(audio.shape[1] / SR, 1),
        lufs=round(loudness(audio), 1),
        peak=round(float(np.max(np.abs(audio))), 3),
        render_s=round(time.time() - t0, 1),
    )


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    preview = None
    if "--preview" in sys.argv:
        preview = sys.argv[sys.argv.index("--preview") + 1]
        args = [a for a in args if a != preview]
    jobs = []
    for a in args or GENRES:
        genre, _, only = a.partition(":")
        mod = importlib.import_module(f"genres.{genre}")
        for c in mod.TRACKS:
            if not only or c["slug"] == only:
                jobs.append((genre, c["slug"]))
    with ProcessPoolExecutor(max_workers=min(6, len(jobs))) as ex:
        results = list(ex.map(job, *zip(*jobs), [preview] * len(jobs)))
    for r in results:
        print(f"{r['genre']:10s} {r['slug']:24s} {r['seconds']:6.1f}s  {r['lufs']:6.1f} LUFS  peak {r['peak']:.3f}  ({r['render_s']}s)")

    write_library()


def write_library():
    """Regenerate src/lib/music-library.ts from whatever MP3s exist."""
    lines = [
        "// Generated by scripts/music-gen/render.py — re-run it instead of editing by hand.",
        "// The bundled tracks each genre's playlist offers (files live in public/music).",
        'import type { MusicGenre } from "./link-store";',
        "",
        "export const MUSIC_LIBRARY: Record<MusicGenre, { label: string; url: string }[]> = {",
    ]
    for genre in GENRES:
        mod = importlib.import_module(f"genres.{genre}")
        lines.append(f"  {genre}: [")
        for c in mod.TRACKS:
            if (OUT / genre / f"{c['slug']}.mp3").exists():
                lines.append(f"    {{ label: {json.dumps(c['title'])}, url: \"/music/{genre}/{c['slug']}.mp3\" }},")
        lines.append("  ],")
    lines.append("};")
    # bytes, so Windows doesn't turn it into CRLF (the repo is LF; prettier enforces it)
    (HERE.parent.parent / "src" / "lib" / "music-library.ts").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
